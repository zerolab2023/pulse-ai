"""의료광고법(의료법 제56조 등) 위험 표현 룰셋 v1.

건강검진·내과 블로그에서 자주 걸리는 위반 유형을 정규식으로 잡고,
왜 위험한지(근거)와 어떻게 바꿀지(대체 문구)를 함께 제공한다.

심각도(severity):
  - "block" : 사실상 위법 소지가 커 발행 차단(fail-closed). 사람 검토 없이는 못 나감.
  - "warn"  : 맥락에 따라 위법이 될 수 있어 검토 필요. 자동 차단은 아니되 경고.

주의: 이 룰셋은 '1차 필터'다. 최종 판단은 의료광고 사전심의/의료인 감수를 대체하지 않는다.
근거 요약은 참고용이며 법률 자문이 아니다.
"""
from __future__ import annotations

from dataclasses import dataclass


@dataclass
class Rule:
    category: str        # 위반 유형
    pattern: str         # 정규식 (re.IGNORECASE로 매칭)
    severity: str        # "block" | "warn"
    reason: str          # 왜 위험한지(근거 요약)
    suggestion: str      # 대체 방향/문구


# 규칙 순서 = 대략적인 위험도 순.
RULES: list[Rule] = [
    # 1) 치료경험담·후기 (의료법 제56조: 치료효과 오인 우려 → 금지)
    Rule(
        category="치료경험담/후기",
        pattern=r"(후기|치료\s*경험담|시술\s*후기|검진\s*후기|다녀왔[어요습]|받아봤[어요습])",
        severity="block",
        reason="환자 치료경험담·후기는 치료효과 오인 우려로 금지될 수 있음(대가 수수 무관).",
        suggestion="개인 경험 서술 대신 '검진 항목/절차의 일반 정보'로 전환. 예: '위내시경은 이렇게 진행됩니다'.",
    ),
    # 2) 치료효과 오인·과장·절대적 표현
    Rule(
        category="치료효과 오인/과장",
        pattern=r"(완치|100\s*%|100퍼|부작용\s*(이)?\s*없|무통증|통증\s*없|안전\s*보장|보장(합니다|해요|됩니다)?)",
        severity="block",
        reason="완치·부작용 없음·보장 등은 효과를 단정해 소비자를 오인시킬 수 있어 금지.",
        suggestion="단정 대신 사실 기반으로. 예: '개인차가 있습니다', '드물게 불편감이 있을 수 있습니다'.",
    ),
    # 3) 최상급·비교우위 (최고/유일/1위/제일)
    Rule(
        category="최상급/비교광고",
        pattern=r"(최고|최상|유일(한|무이)?|국내\s*최초|업계\s*1위|1위|제일\s*잘|가장\s*(좋|우수))",
        severity="block",
        reason="객관적 근거 없는 최상급·비교우위 표현은 과장광고로 제재 대상.",
        suggestion="근거 있는 사실로 대체. 예: '3T MRI 보유', '국가검진 지정기관' 등 검증 가능한 표현.",
    ),
    # 4) 환자 유인·알선 (비급여 할인/이벤트/무료 강조)
    Rule(
        category="환자 유인/할인",
        pattern=r"(이벤트|할인|특가|무료\s*(검진|시술|진료)|사은품|경품|선착순|프로모션|%\s*할인)",
        severity="warn",
        reason="비급여 진료의 과도한 할인·이벤트성 유인은 환자 유인행위로 볼 수 있음.",
        suggestion="가격 유인 대신 정보 제공 중심으로. 국가검진 등 급여 항목 안내는 사실 기반으로만.",
    ),
    # 5) 전문의/1등급 등 자격·인증 과장
    Rule(
        category="자격/인증 과장",
        pattern=r"(명의|권위자|대한민국\s*대표|정부\s*공인|보건복지부\s*인증)",
        severity="warn",
        reason="공인·대표 등 검증 어려운 권위 표현은 오인 소지가 있음.",
        suggestion="검증 가능한 자격만 표기. 예: '내과 전문의', '건강검진 지정 의료기관'.",
    ),
    # 6) 진단·처방을 단정하는 비의료인 서술 (마케터 명의 글 주의)
    Rule(
        category="비의료인 의학적 단정",
        pattern=r"(반드시\s*(수술|시술|치료)|무조건\s*(검사|치료)|꼭\s*받아야|이\s*약을\s*드세요)",
        severity="warn",
        reason="의학적 판단·처방을 단정하는 서술은 의료인 명의·감수가 필요.",
        suggestion="권유·단정 대신 '전문의 상담 권장' 톤으로. 의학 판단 서술은 의료인 감수 필수.",
    ),
]
